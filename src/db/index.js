/** Violação de UNIQUE / FOREIGN KEY / CHECK (classe 23 do PostgreSQL: 23505, 23503, 23514...). */
export const isConstraintError = (err) => typeof err?.code === 'string' && err.code.startsWith('23');

const isLocalHost = (url) => /@(localhost|127\.0\.0\.1|\[::1\])(:|\/|$)/i.test(url);

/**
 * Cria o acesso ao banco. A interface é pequena de propósito:
 *   db.all(sql, params)  -> lista de linhas
 *   db.get(sql, params)  -> primeira linha (ou undefined)
 *   db.run(sql, params)  -> número de linhas afetadas
 *   db.transaction(fn)   -> fn recebe um objeto com all/get/run; COMMIT se tudo der certo, ROLLBACK se lançar erro
 *   db.close()           -> encerra as conexões
 * Use $1, $2... nos parâmetros (nunca monte SQL concatenando texto do usuário).
 */
export function createDb(connectionString, { ssl, max = 10, searchPath } = {}) {
  if (!connectionString) throw new Error('DATABASE_URL não definida.');

  // O SSL é controlado pela opção `ssl` abaixo, então ignoramos o ?sslmode= da URL.
  const url = connectionString.replace(/([?&])sslmode=[^&]*&?/i, '$1').replace(/[?&]$/, '');
  const useSsl = ssl ?? !isLocalHost(url);

  const pool = new pg.Pool({
    connectionString: url,
    max,
    idleTimeoutMillis: 30_000,
    connectionTimeoutMillis: 5_000, // ALTERADO AQUI (de 10_000 para 5_000)
    // Supabase exige SSL. A conexão é criptografada; o certificado do pooler não é validado aqui.
    ssl: useSsl ? { rejectUnauthorized: false } : false,
    ...(searchPath && { options: `-c search_path=${searchPath}` }),
  });
  // Sem isso, uma conexão ociosa derrubada pelo servidor encerraria o processo inteiro.
  pool.on('error', (err) => console.error('[db] erro em conexão ociosa:', err.message));

  const api = (runner) => ({
    all: async (sql, params = []) => (await runner.query(sql, params)).rows,
    get: async (sql, params = []) => (await runner.query(sql, params)).rows[0],
    run: async (sql, params = []) => (await runner.query(sql, params)).rowCount,
  });

  return {
    pool,
    ...api(pool),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn(api(client));
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

/** Aplica as migrações pendentes. O lock impede que duas instâncias migrem ao mesmo tempo. */
export async function migrate(db) {
  const client = await db.pool.connect();
  try {
    await client.query('SELECT pg_advisory_lock(727274)');
    await client.query(
      'CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())',
    );
    const { rows } = await client.query('SELECT COALESCE(MAX(version), 0)::int AS v FROM schema_migrations');
    for (let version = rows[0].v; version < MIGRATIONS.length; version++) {
      try {
        await client.query('BEGIN');
        await client.query(MIGRATIONS[version]);
        await client.query('INSERT INTO schema_migrations (version) VALUES ($1)', [version + 1]);
        await client.query('COMMIT');
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      }
    }
  } finally {
    await client.query('SELECT pg_advisory_unlock(727274)').catch(() => {});
    client.release();
  }
}

/** Cria as comunidades oficiais e a conta admin se ainda não existirem. */
export async function seed(db) {
  await db.transaction(async (tx) => {
    const { n } = await tx.get('SELECT COUNT(*)::int AS n FROM communities');
    if (n === 0) {
      for (const [name, description] of SEED_COMMUNITIES) {
        await tx.run(
          'INSERT INTO communities (name, description, is_official) VALUES ($1, $2, true) ON CONFLICT DO NOTHING',
          [name, description],
        );
      }
    }
  });

  // Conta admin: só cria se não houver nenhum administrador ainda.
  const { n: admins } = await db.get('SELECT COUNT(*)::int AS n FROM users WHERE is_admin = true');
  if (admins === 0) {
    const existing = await db.get('SELECT id FROM users WHERE email = $1', [ADMIN_SEED.email]);
    if (existing) {
      await db.run('UPDATE users SET is_admin = true WHERE id = $1', [existing.id]);
    } else {
      const passwordHash = await hashPassword(ADMIN_SEED.password);
      await db.run(
        'INSERT INTO users (name, email, password_hash, is_admin) VALUES ($1, $2, $3, true)',
        [ADMIN_SEED.name, ADMIN_SEED.email, passwordHash],
      );
    }
  }
}

/** Conecta, confere a conexão, cria/atualiza as tabelas e semeia as comunidades oficiais. */
export async function openDatabase(connectionString, options) {
  const db = createDb(connectionString, options);
  try {
    await db.get('SELECT 1');
    await migrate(db);
    await seed(db);
  } catch (err) {
    await db.close().catch(() => {});
    throw err;
  }
  return db;
}